bool resolveNativeToolchainSelection(const std::string& projectRoot,
                                     const ProjectManifestData* manifest,
                                     const PackageRegistryEntry& entry,
                                     const InstallOptions* options,
                                     NativeToolchainSelection& outSelection,
                                     std::string& outError) {
    outSelection = NativeToolchainSelection{};
    outSelection.target =
        entry.selectedTarget.empty() ? effectiveInstallTarget(options)
                                     : entry.selectedTarget;
    if (outSelection.target.empty()) {
        outSelection.target = detectHostTarget();
    }

    std::filesystem::path toolchainPath;
    if (options != nullptr && !options->cmakeToolchainFile.empty()) {
        toolchainPath = std::filesystem::path(options->cmakeToolchainFile);
        outSelection.sourceDescription = "--cmake-toolchain";
    } else if (manifest != nullptr && outSelection.target != detectHostTarget()) {
        const ProjectNativeToolchainConfig* config =
            findNativeToolchainConfig(*manifest, outSelection.target);
        if (config != nullptr && !config->cmakeToolchain.empty()) {
            toolchainPath = std::filesystem::path(projectRoot) /
                            std::filesystem::path(config->cmakeToolchain);
            outSelection.sourceDescription =
                nativeToolchainSettingLabel(outSelection.target);
        }
        if (toolchainPath.empty()) {
            const std::string envName =
                "MOG_CMAKE_TOOLCHAIN_" + normalizeEnvKey(outSelection.target);
            if (const char* envValue = std::getenv(envName.c_str());
                envValue != nullptr && *envValue != '\0') {
                toolchainPath = std::filesystem::path(envValue);
                outSelection.sourceDescription = "$" + envName;
            } else {
                outSelection.checkedSources.push_back("$" + envName);
            }
        }
        if (toolchainPath.empty()) {
            const std::filesystem::path projectMogToolchain =
                std::filesystem::path(projectRoot) / ".mog" / "toolchains" /
                (outSelection.target + ".cmake");
            if (fileExists(projectMogToolchain)) {
                toolchainPath = projectMogToolchain;
                outSelection.sourceDescription =
                    normalizeRelativePath(projectMogToolchain.lexically_relative(
                                              std::filesystem::path(projectRoot))
                                              .string());
            } else {
                outSelection.checkedSources.push_back(
                    normalizeRelativePath(projectMogToolchain.lexically_relative(
                                              std::filesystem::path(projectRoot))
                                              .string()));
            }
        }
        if (toolchainPath.empty()) {
            const std::filesystem::path projectToolchain =
                std::filesystem::path(projectRoot) / "toolchains" /
                (outSelection.target + ".cmake");
            if (fileExists(projectToolchain)) {
                toolchainPath = projectToolchain;
                outSelection.sourceDescription =
                    normalizeRelativePath(projectToolchain.lexically_relative(
                                              std::filesystem::path(projectRoot))
                                              .string());
            } else {
                outSelection.checkedSources.push_back(
                    normalizeRelativePath(projectToolchain.lexically_relative(
                                              std::filesystem::path(projectRoot))
                                              .string()));
            }
        }
    }

    if (toolchainPath.empty()) {
        return true;
    }

    const std::string resolvedToolchain = canonicalOrLexical(toolchainPath);
    if (!fileExists(resolvedToolchain)) {
        std::ostringstream details;
        if (!outSelection.checkedSources.empty()) {
            details << " Checked: ";
            for (size_t index = 0; index < outSelection.checkedSources.size();
                 ++index) {
                if (index != 0) {
                    details << ", ";
                }
                details << outSelection.checkedSources[index];
            }
            details << ".";
        }
        outError = buildNativeSourceFallbackPrefix(entry) +
                   " could not find CMake toolchain file '" +
                   resolvedToolchain + "' configured via " +
                   outSelection.sourceDescription + "." + details.str();
        return false;
    }

    outSelection.cmakeToolchainFile = resolvedToolchain;
    return true;
}

bool isExactPublishedVersion(std::string_view version) {
    if (version.empty()) {
        return false;
    }

    size_t componentCount = 0;
    size_t componentLength = 0;
    for (char ch : version) {
        if (ch == '.') {
            if (componentLength == 0) {
                return false;
            }
            ++componentCount;
            componentLength = 0;
            continue;
        }
        if (!std::isdigit(static_cast<unsigned char>(ch))) {
            return false;
        }
        ++componentLength;
    }

    return componentLength > 0 && componentCount == 2;
}

bool parseSemanticVersion(std::string_view text, SemanticVersion& outVersion) {
    outVersion = SemanticVersion{};
    if (!isExactPublishedVersion(text)) {
        return false;
    }

    std::string component;
    std::vector<int> values;
    std::stringstream stream{std::string(text)};
    while (std::getline(stream, component, '.')) {
        try {
            values.push_back(std::stoi(component));
        } catch (const std::exception&) {
            return false;
        }
    }

    if (values.size() != 3) {
        return false;
    }

    outVersion.major = values[0];
    outVersion.minor = values[1];
    outVersion.patch = values[2];
    return true;
}

int compareSemanticVersions(const SemanticVersion& lhs,
                           const SemanticVersion& rhs) {
    if (lhs.major != rhs.major) {
        return lhs.major < rhs.major ? -1 : 1;
    }
    if (lhs.minor != rhs.minor) {
        return lhs.minor < rhs.minor ? -1 : 1;
    }
    if (lhs.patch != rhs.patch) {
        return lhs.patch < rhs.patch ? -1 : 1;
    }
    return 0;
}

bool parseVersionRequirement(std::string_view text, VersionRequirement& outRequirement,
                             std::string& outError) {
    outRequirement = VersionRequirement{};
    outRequirement.raw = std::string(text);
    if (text.empty()) {
        outRequirement.kind = VersionRequirement::Kind::ANY;
        return true;
    }

    VersionRequirement::Kind kind = VersionRequirement::Kind::EXACT;
    if (text.front() == '^') {
        kind = VersionRequirement::Kind::CARET;
        text.remove_prefix(1);
    } else if (text.front() == '~') {
        kind = VersionRequirement::Kind::TILDE;
        text.remove_prefix(1);
    }

    if (!parseSemanticVersion(text, outRequirement.version)) {
        outError = "Version requirements must use x.y.z, ^x.y.z, or ~x.y.z.";
        return false;
    }

    outRequirement.kind = kind;
    return true;
}

bool versionSatisfiesRequirement(const SemanticVersion& version,
                                 const VersionRequirement& requirement) {
    switch (requirement.kind) {
        case VersionRequirement::Kind::ANY:
            return true;
        case VersionRequirement::Kind::EXACT:
            return compareSemanticVersions(version, requirement.version) == 0;
        case VersionRequirement::Kind::CARET:
            if (version.major != requirement.version.major) {
                return false;
            }
            return compareSemanticVersions(version, requirement.version) >= 0;
        case VersionRequirement::Kind::TILDE:
            if (version.major != requirement.version.major ||
                version.minor != requirement.version.minor) {
                return false;
            }
            return compareSemanticVersions(version, requirement.version) >= 0;
    }
    return false;
}

bool parseRegistryDependencyPin(std::string_view text,
                                RegistryDependencyPin& outPin,
                                std::string& outError) {
    outPin = RegistryDependencyPin{};
    const size_t at = text.rfind('@');
    if (at == std::string_view::npos || at == 0 || at + 1 >= text.size()) {
        outError = "Registry dependency pins must use 'namespace:name@x.y.z'.";
        return false;
    }

    outPin.packageId = std::string(text.substr(0, at));
    outPin.version = std::string(text.substr(at + 1));
    if (!isExactPublishedVersion(outPin.version)) {
        outError = "Registry dependency pin '" + std::string(text) +
                   "' must use an exact x.y.z version.";
        return false;
    }
    return true;
}

bool parseDependencyInlineTable(const std::string& value,
                                DependencySpec& outDependency,
                                std::string& outError) {
    if (value.size() < 2 || value.front() != '{' || value.back() != '}') {
        outError = "Dependency entries must be inline tables.";
        return false;
    }

    std::string body = trim(std::string_view(value).substr(1, value.size() - 2));
    while (!body.empty()) {
        const size_t equals = body.find('=');
        if (equals == std::string::npos) {
            outError = "Dependency table must use key = value entries.";
            return false;
        }

        const std::string key = trim(std::string_view(body).substr(0, equals));
        body = trim(std::string_view(body).substr(equals + 1));
        if (body.empty()) {
            outError = "Dependency table entry is missing a value.";
            return false;
        }

        size_t valueLength = 0;
        bool inString = false;
        bool escaped = false;
        for (; valueLength < body.size(); ++valueLength) {
            const char ch = body[valueLength];
            if (inString) {
                if (escaped) {
                    escaped = false;
                } else if (ch == '\\') {
                    escaped = true;
                } else if (ch == '"') {
                    inString = false;
                }
                continue;
            }

            if (ch == '"') {
                inString = true;
                continue;
            }

            if (ch == ',') {
                break;
            }
        }

        const std::string rawValue = trim(body.substr(0, valueLength));
        if (key == "path") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.path = normalizeRelativePath(parsed);
        } else if (key == "package") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.packageId = parsed;
        } else if (key == "version") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.version = parsed;
        } else if (key == "git") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.git = parsed;
        } else if (key == "rev") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.gitRev = parsed;
        } else if (key == "tag") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.gitTag = parsed;
        } else if (key == "branch") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.gitBranch = parsed;
        } else if (key == "registry") {
            std::string parsed;
            if (!parseQuotedString(rawValue, parsed, outError)) {
                return false;
            }
            outDependency.registry = parsed;
        } else if (key == "workspace") {
            if (!parseBoolValue(rawValue, outDependency.workspace, outError)) {
                return false;
            }
        } else {
            outError = "Unsupported dependency field '" + key + "'.";
            return false;
        }

        if (valueLength >= body.size()) {
            body.clear();
        } else {
            body = trim(std::string_view(body).substr(valueLength + 1));
        }
    }

    if (outDependency.path.empty() && !outDependency.workspace &&
        outDependency.git.empty() && outDependency.registry.empty() &&
        outDependency.packageId.empty()) {
        outError = "Dependency entries must define path, workspace, git, registry, or package metadata.";
        return false;
    }

    return validateDependencySpec(outDependency, outError);
}

