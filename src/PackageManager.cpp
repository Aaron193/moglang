bool resolveEffectiveRegistryProfile(const std::string& projectRoot,
                                     const ProjectRegistryConfig& config,
                                     EffectiveRegistryProfile& outProfile,
                                     std::string& outError) {
    outProfile = EffectiveRegistryProfile{};
    outError.clear();
    outProfile.config = config;

    if (!resolveRegistryIdentity(projectRoot, config, outProfile.normalizedIndex,
                                 outProfile.isRemote, outError)) {
        return false;
    }

    UserRegistryConfigData userConfig;
    if (!loadUserRegistryProfiles(userConfig, outError)) {
        return false;
    }
    const UserRegistryProfile* userProfile =
        findUserRegistryProfile(userConfig, outProfile.normalizedIndex);

    outProfile.trustFromProject = !config.trustedKeys.empty();
    outProfile.trustFromUser =
        userProfile != nullptr && !userProfile->trustedKeys.empty();
    if (userProfile != nullptr) {
        outProfile.config.trustedKeys.insert(outProfile.config.trustedKeys.end(),
                                             userProfile->trustedKeys.begin(),
                                             userProfile->trustedKeys.end());
    }
    outProfile.config.trustedKeys =
        sortedUniqueStrings(std::move(outProfile.config.trustedKeys));
    outProfile.config.index = outProfile.normalizedIndex;

    if (!parseTrustedKeyIds(outProfile.config.trustedKeys,
                            outProfile.trustedKeyIds, outError)) {
        outError = "Registry '" + config.alias + "' has invalid trusted_keys: " +
                   outError;
        return false;
    }

    if (!resolveRegistryAuthTokenForIndex(config.alias, outProfile.normalizedIndex,
                                          outProfile.token, outError)) {
        return false;
    }
    outProfile.hasToken = !outProfile.token.empty();

    return true;
}

bool resolveRegistryAuthTokenForIndex(std::string_view alias,
                                      std::string_view normalizedIndex,
                              std::string& outToken,
                              std::string& outError) {
    outToken.clear();
    outError.clear();

    const std::string envAlias =
        "MOG_REGISTRY_TOKEN_" + normalizeEnvKey(alias);
    if (const char* specific = std::getenv(envAlias.c_str());
        specific != nullptr && *specific != '\0') {
        outToken = specific;
        return true;
    }
    if (const char* generic = std::getenv("MOG_REGISTRY_TOKEN");
        generic != nullptr && *generic != '\0') {
        outToken = generic;
        return true;
    }

    UserRegistryConfigData userConfig;
    if (!loadUserRegistryProfiles(userConfig, outError)) {
        return false;
    }
    const UserRegistryProfile* userProfile =
        findUserRegistryProfile(userConfig, normalizedIndex);
    if (userProfile != nullptr && !userProfile->token.empty()) {
        outToken = userProfile->token;
        return true;
    }

    std::unordered_map<std::string, std::string> tokens;
    if (!loadLegacyRegistryAuthTokens(tokens, outError)) {
        return false;
    }
    auto it = tokens.find(std::string(alias));
    if (it != tokens.end()) {
        outToken = it->second;
    }
    return true;
}

bool resolveRegistryAuthToken(const std::string& projectRoot,
                              const ProjectRegistryConfig& config,
                              std::string& outToken,
                              std::string& outError) {
    std::string normalizedIndex;
    bool isRemote = false;
    if (!resolveRegistryIdentity(projectRoot, config, normalizedIndex, isRemote,
                                 outError)) {
        return false;
    }
    if (!resolveRegistryAuthTokenForIndex(config.alias, normalizedIndex, outToken,
                                          outError)) {
        return false;
    }
    return true;
}

bool loadRegistryIndex(const std::string& projectRoot,
                       const ProjectRegistryConfig& config,
                       const InstallOptions* options,
                       LoadedRegistryIndex& outIndex,
                       std::string& outError) {
    outIndex = LoadedRegistryIndex{};
    outError.clear();

    EffectiveRegistryProfile effectiveProfile;
    if (!resolveEffectiveRegistryProfile(projectRoot, config, effectiveProfile,
                                         outError)) {
        return false;
    }

    RegistryLocation location;
    if (!resolveRegistryLocation(projectRoot, effectiveProfile.config, location,
                                 outError)) {
        return false;
    }

    std::filesystem::path configuredPath = location.localIndexPath;
    std::error_code ec;
    if (location.isRemote) {
        const bool offline = options != nullptr && options->offline;
        if (offline && !fileExists(configuredPath)) {
            outError = "Registry '" + config.alias +
                       "' cannot be used with --offline because its index is not cached locally.";
            return false;
        }
        if (!offline || !fileExists(configuredPath)) {
            if (!downloadUrlToFile(location.remoteIndexUrl, effectiveProfile.token,
                                   configuredPath, outError)) {
                outError = "Registry '" + config.alias +
                           "' index download failed: " + outError;
                return false;
            }
        }
    }
    if (ec || !std::filesystem::exists(configuredPath, ec) || ec) {
        outError = "Registry '" + config.alias + "' index does not exist at '" +
                   configuredPath.lexically_normal().string() + "'.";
        return false;
    }

    outIndex.indexPath = configuredPath;
    outIndex.rootDir = location.localRootDir;
    outIndex.isRemote = location.isRemote;
    outIndex.remoteIndexUrl = location.remoteIndexUrl;
    outIndex.remoteRootUrl = location.remoteRootUrl;

    std::ifstream file(configuredPath);
    if (!file) {
        outError = "Could not open registry index '" + configuredPath.string() + "'.";
        return false;
    }

    RegistryIndexRecord current;
    bool hasCurrent = false;
    std::string line;
    size_t lineNumber = 0;

    auto flushCurrent = [&]() -> bool {
        if (!hasCurrent) {
            return true;
        }
        const bool hasPrimaryArtifact =
            !current.artifactPath.empty() || !current.artifactDigest.empty();
        const bool hasNativeArtifacts = !current.nativeTargets.empty() ||
                                       !current.nativeArtifactPaths.empty() ||
                                       !current.nativeArtifactDigests.empty();
        if (current.packageId.empty() || current.version.empty() ||
            (!hasPrimaryArtifact && !hasNativeArtifacts)) {
            outError = "Registry '" + config.alias +
                       "' index entries must define package_id, version, and at least one artifact.";
            return false;
        }
        if ((!current.artifactPath.empty() && current.artifactDigest.empty()) ||
            (current.artifactPath.empty() && !current.artifactDigest.empty())) {
            outError = "Registry '" + config.alias +
                       "' source artifact entries must define both artifact_path and artifact_digest.";
            return false;
        }
        if (!current.artifactDigest.empty() && !isSecureDigest(current.artifactDigest)) {
            outError = "Registry '" + config.alias + "' package '" +
                       current.packageId +
                       "' must use sha256-prefixed artifact digests.";
            return false;
        }
        if (current.nativeTargets.size() != current.nativeArtifactPaths.size() ||
            current.nativeTargets.size() != current.nativeArtifactDigests.size()) {
            outError = "Registry '" + config.alias +
                       "' native artifact fields must define the same number of targets, paths, and digests.";
            return false;
        }
        for (const std::string& nativeDigest : current.nativeArtifactDigests) {
            if (!isSecureDigest(nativeDigest)) {
                outError = "Registry '" + config.alias + "' package '" +
                           current.packageId +
                           "' must use sha256-prefixed native artifact digests.";
                return false;
            }
        }
        if (!isExactPublishedVersion(current.version)) {
            outError = "Registry '" + config.alias + "' package '" +
                       current.packageId + "' must use an exact x.y.z version.";
            return false;
        }
        if (!parseSemanticVersion(current.version, current.parsedVersion)) {
            outError = "Registry '" + config.alias + "' package '" +
                       current.packageId + "' must use an exact x.y.z version.";
            return false;
        }
        const std::string key = registryRecordKey(current.packageId, current.version);
        if (!outIndex.recordsByKey.emplace(key, current).second) {
            outError = "Registry '" + config.alias + "' contains a duplicate entry for '" +
                       key + "'.";
            return false;
        }
        outIndex.recordsByPackageId[current.packageId].push_back(current);
        current = RegistryIndexRecord{};
        hasCurrent = false;
        return true;
    };

    while (std::getline(file, line)) {
        ++lineNumber;
        const std::string content = stripComment(line);
        if (content.empty()) {
            continue;
        }

        if (content == "[[package]]") {
            if (!flushCurrent()) {
                return false;
            }
            hasCurrent = true;
            continue;
        }

        const size_t equals = content.find('=');
        if (equals == std::string::npos) {
            outError = "Invalid registry index line " + std::to_string(lineNumber) +
                       ": expected key = value.";
            return false;
        }

        const std::string key = trim(std::string_view(content).substr(0, equals));
        const std::string value =
            trim(std::string_view(content).substr(equals + 1));

        if (!hasCurrent) {
            if (key == "schema_version") {
                if (!parseQuotedString(value, outIndex.schemaVersion, outError)) {
                    outError = "Invalid registry index line " +
                               std::to_string(lineNumber) + ": " + outError;
                    return false;
                }
                continue;
            }
            if (key == "signing_key_id") {
                if (!parseQuotedString(value, outIndex.signingKeyId, outError)) {
                    outError = "Invalid registry index line " +
                               std::to_string(lineNumber) + ": " + outError;
                    return false;
                }
                continue;
            }
            if (key == "signature") {
                if (!parseQuotedString(value, outIndex.signatureBase64, outError)) {
                    outError = "Invalid registry index line " +
                               std::to_string(lineNumber) + ": " + outError;
                    return false;
                }
                continue;
            }
            outError = "Invalid registry index line " + std::to_string(lineNumber) +
                       ": entries must appear inside [[package]].";
            return false;
        }

        if (key == "dependencies") {
            std::vector<std::string> pins;
            if (!parseQuotedStringArray(value, pins, outError)) {
                outError = "Invalid registry index line " +
                           std::to_string(lineNumber) + ": " + outError;
                return false;
            }
            current.dependencies.clear();
            for (const std::string& pinText : pins) {
                RegistryDependencyPin pin;
                if (!parseRegistryDependencyPin(pinText, pin, outError)) {
                    outError = "Invalid registry index line " +
                               std::to_string(lineNumber) + ": " + outError;
                    return false;
                }
                current.dependencies.push_back(std::move(pin));
            }
            continue;
        }

        if (key == "native_targets") {
            if (!parseQuotedStringArray(value, current.nativeTargets, outError)) {
                outError = "Invalid registry index line " +
                           std::to_string(lineNumber) + ": " + outError;
                return false;
            }
            continue;
        }
        if (key == "native_artifact_paths") {
            if (!parseQuotedStringArray(value, current.nativeArtifactPaths,
                                        outError)) {
                outError = "Invalid registry index line " +
                           std::to_string(lineNumber) + ": " + outError;
                return false;
            }
            continue;
        }
        if (key == "native_artifact_digests") {
            if (!parseQuotedStringArray(value, current.nativeArtifactDigests,
                                        outError)) {
                outError = "Invalid registry index line " +
                           std::to_string(lineNumber) + ": " + outError;
                return false;
            }
            continue;
        }

        std::string parsed;
        if (!parseQuotedString(value, parsed, outError)) {
            outError = "Invalid registry index line " + std::to_string(lineNumber) +
                       ": " + outError;
            return false;
        }

        if (key == "package_id") {
            current.packageId = parsed;
        } else if (key == "version") {
            current.version = parsed;
        } else if (key == "artifact_path") {
            current.artifactPath = parsed;
        } else if (key == "artifact_digest") {
            current.artifactDigest = parsed;
        } else {
            outError = "Unsupported registry index field '" + key + "'.";
            return false;
        }
    }

    if (!flushCurrent()) {
        return false;
    }

    for (auto& [packageId, records] : outIndex.recordsByPackageId) {
        std::sort(records.begin(), records.end(),
                  [](const RegistryIndexRecord& lhs,
                     const RegistryIndexRecord& rhs) {
                      return compareSemanticVersions(lhs.parsedVersion,
                                                     rhs.parsedVersion) > 0;
                  });
    }

    if (outIndex.schemaVersion != "registry.v1" &&
        outIndex.schemaVersion != "registry.v2") {
        outError = "Registry '" + config.alias + "' uses unsupported schema '" +
                   outIndex.schemaVersion + "'.";
        return false;
    }

    if (outIndex.schemaVersion == "registry.v2") {
        std::vector<RegistryIndexRecord> canonicalRecords;
        canonicalRecords.reserve(outIndex.recordsByKey.size());
        for (const auto& [key, record] : outIndex.recordsByKey) {
            canonicalRecords.push_back(record);
        }
        const std::string canonicalPayload =
            canonicalRegistryIndexPayload(std::move(canonicalRecords));
        if (!verifyRegistrySignatureEnvelope(effectiveProfile.config, location.isRemote,
                                             outIndex.signingKeyId,
                                             outIndex.signatureBase64,
                                             canonicalPayload, outError)) {
            return false;
        }
    } else if (registryRequiresTrustedSignatures(effectiveProfile.config,
                                                 location.isRemote)) {
        outError = "Registry '" + config.alias +
                   "' requires a signed registry.v2 index, but the registry is unsigned.";
        return false;
    }

    return true;
}

bool resolveRegistryIndexLocation(const std::string& projectRoot,
                                  const ProjectRegistryConfig& config,
                                  std::filesystem::path& outIndexPath,
                                  std::filesystem::path& outRootDir,
                                  std::string& outError) {
    RegistryLocation location;
    if (!resolveRegistryLocation(projectRoot, config, location, outError)) {
        return false;
    }
    outIndexPath = location.localIndexPath.lexically_normal();
    outRootDir = location.localRootDir.lexically_normal();
    return true;
}

bool writeAdvisoriesFile(const std::filesystem::path& outputPath,
                         const std::vector<AdvisoryRecord>& records,
                         const RegistrySigningKeyFile& signingKey,
                         std::string& outError) {
    std::error_code ec;
    std::filesystem::create_directories(outputPath.parent_path(), ec);
    if (ec) {
        outError = "Could not create advisory directory '" +
                   outputPath.parent_path().string() + "'.";
        return false;
    }

    const std::string canonicalPayload = canonicalAdvisoriesPayload(records);
    std::string signatureBase64;
    if (!signEd25519Message(signingKey.privateKeyDerBase64, canonicalPayload,
                            signatureBase64, outError)) {
        outError = "Could not sign advisories: " + outError;
        return false;
    }

    std::ofstream out(outputPath);
    if (!out) {
        outError = "Could not open advisory file '" + outputPath.string() +
                   "' for writing.";
        return false;
    }

    out << "schema_version = " << quoteTomlString("advisories.v1") << "\n";
    out << "signing_key_id = " << quoteTomlString(signingKey.keyId) << "\n";
    out << "signature = " << quoteTomlString(signatureBase64) << "\n";
    out << canonicalPayload.substr(canonicalPayload.find('\n') + 1);
    return true;
}

bool advisoryMatchesVersion(const AdvisoryRecord& record,
                            std::string_view version,
                            std::string& outError) {
    VersionRequirement requirement;
    if (!parseVersionRequirement(record.affected, requirement, outError)) {
        return false;
    }
    SemanticVersion parsedVersion;
    if (!parseSemanticVersion(std::string(version), parsedVersion)) {
        outError = "Installed package version '" + std::string(version) +
                   "' is not a valid semantic version.";
        return false;
    }
    return versionSatisfiesRequirement(parsedVersion, requirement);
}

bool loadRegistryAdvisories(const std::string& projectRoot,
                            const ProjectRegistryConfig& config,
                            const AuditOptions& options,
                            LoadedRegistryAdvisories& outAdvisories,
                            std::string& outError) {
    outAdvisories = LoadedRegistryAdvisories{};
    outError.clear();

    EffectiveRegistryProfile effectiveProfile;
    if (!resolveEffectiveRegistryProfile(projectRoot, config, effectiveProfile,
                                         outError)) {
        return false;
    }

    RegistryLocation location;
    if (!resolveRegistryLocation(projectRoot, effectiveProfile.config, location,
                                 outError)) {
        return false;
    }

    std::filesystem::path advisoriesPath = location.isRemote
                                               ? remoteRegistryAdvisoriesCachePath(
                                                     config.alias, location.remoteRootUrl)
                                               : location.localRootDir / "advisories.toml";

    if (location.isRemote) {
        if (options.offline && !fileExists(advisoriesPath)) {
            outError = "Registry '" + config.alias +
                       "' cannot be audited with --offline because advisories are not cached locally.";
            return false;
        }
        if (!options.offline || !fileExists(advisoriesPath)) {
            std::string downloadError;
            if (!downloadUrlToFile(joinUrlPath(location.remoteRootUrl, "advisories.toml"),
                                   effectiveProfile.token, advisoriesPath,
                                   downloadError)) {
                if (downloadError.find("404") != std::string::npos) {
                    return true;
                }
                outError = "Registry '" + config.alias +
                           "' advisory download failed: " + downloadError;
                return false;
            }
        }
    } else if (!fileExists(advisoriesPath)) {
        return true;
    }

    outAdvisories.advisoriesPath = advisoriesPath;
    outAdvisories.isRemote = location.isRemote;

    std::ifstream file(advisoriesPath);
    if (!file) {
        outError = "Could not open advisory file '" + advisoriesPath.string() + "'.";
        return false;
    }

    AdvisoryRecord current;
    bool hasCurrent = false;
    std::string line;
    size_t lineNumber = 0;

    auto flushCurrent = [&]() -> bool {
        if (!hasCurrent) {
            return true;
        }
        if (current.id.empty() || current.packageId.empty() || current.affected.empty() ||
            current.severity.empty() || current.summary.empty()) {
            outError = "Registry '" + config.alias +
                       "' advisory entries must define id, package_id, affected, severity, and summary.";
            return false;
        }
        outAdvisories.records.push_back(current);
        current = AdvisoryRecord{};
        hasCurrent = false;
        return true;
    };

    while (std::getline(file, line)) {
        ++lineNumber;
        const std::string content = stripComment(line);
        if (content.empty()) {
            continue;
        }

        if (content == "[[advisory]]") {
            if (!flushCurrent()) {
                return false;
            }
            hasCurrent = true;
            continue;
        }

        const size_t equals = content.find('=');
        if (equals == std::string::npos) {
            outError = "Invalid advisory line " + std::to_string(lineNumber) +
                       ": expected key = value.";
            return false;
        }

        const std::string key = trim(std::string_view(content).substr(0, equals));
        const std::string value = trim(std::string_view(content).substr(equals + 1));

        if (!hasCurrent) {
            std::string parsed;
            if (!parseQuotedString(value, parsed, outError)) {
                outError = "Invalid advisory line " + std::to_string(lineNumber) +
                           ": " + outError;
                return false;
            }
            if (key == "schema_version") {
                outAdvisories.schemaVersion = parsed;
            } else if (key == "signing_key_id") {
                outAdvisories.signingKeyId = parsed;
            } else if (key == "signature") {
                outAdvisories.signatureBase64 = parsed;
            } else {
                outError = "Invalid advisory line " + std::to_string(lineNumber) +
                           ": entries must appear inside [[advisory]].";
                return false;
            }
            continue;
        }

        std::string parsed;
        if (key == "summary" && value.rfind("\"\"\"", 0) == 0) {
            if (!parseMultilineStringValue(value, file, parsed, lineNumber, outError)) {
                outError = "Invalid advisory line " + std::to_string(lineNumber) +
                           ": " + outError;
                return false;
            }
        } else if (!parseQuotedString(value, parsed, outError)) {
            outError = "Invalid advisory line " + std::to_string(lineNumber) +
                       ": " + outError;
            return false;
        }

        if (key == "id") {
            current.id = parsed;
        } else if (key == "package_id") {
            current.packageId = parsed;
        } else if (key == "affected") {
            current.affected = parsed;
        } else if (key == "severity") {
            current.severity = parsed;
        } else if (key == "summary") {
            current.summary = parsed;
        } else if (key == "fixed_version") {
            current.fixedVersion = parsed;
        } else if (key == "url") {
            current.url = parsed;
        } else {
            outError = "Unsupported advisory field '" + key + "'.";
            return false;
        }
    }

    if (!flushCurrent()) {
        return false;
    }

    if (outAdvisories.schemaVersion != "advisories.v1") {
        outError = "Registry '" + config.alias + "' uses unsupported advisory schema '" +
                   outAdvisories.schemaVersion + "'.";
        return false;
    }

    if (!outAdvisories.records.empty()) {
        const std::string canonicalPayload =
            canonicalAdvisoriesPayload(outAdvisories.records);
        if (!verifyRegistrySignatureEnvelope(effectiveProfile.config,
                                             location.isRemote,
                                             outAdvisories.signingKeyId,
                                             outAdvisories.signatureBase64,
                                             canonicalPayload, outError)) {
            return false;
        }
    } else if (registryRequiresTrustedSignatures(effectiveProfile.config,
                                                 location.isRemote) &&
               (outAdvisories.signingKeyId.empty() ||
                outAdvisories.signatureBase64.empty())) {
        outError = "Registry '" + config.alias +
                   "' requires signed advisories metadata when advisories.toml is present.";
        return false;
    }

    return true;
}

bool scanPackageDirectories(const std::filesystem::path& root,
                            std::unordered_map<std::string, PackageNode>& outNodes,
                            std::string& outError) {
    std::error_code ec;
    if (!std::filesystem::exists(root, ec) || ec) {
        return true;
    }

    for (std::filesystem::recursive_directory_iterator it(root, ec), end;
         !ec && it != end; it.increment(ec)) {
        if (ec || !it->is_directory()) {
            continue;
        }

        const std::filesystem::path dir = it->path();
        if (!fileExists(dir / kProjectManifestFileName) &&
            !fileExists(dir / "package.toml")) {
            continue;
        }

        PackageNode node;
        if (!loadPackageEntryFromDir(dir, node.entry, nullptr, outError)) {
            continue;
        }
        if (!loadPackageManifestDependencies(dir, node.manifestDependencies,
                                             outError)) {
            continue;
        }
        node.packageDir = std::filesystem::path(node.entry.packageDir);
        if (!addAvailableNode(outNodes, std::move(node), outError)) {
            return false;
        }
    }

    return true;
}

bool scanWorkspaceMemberPackages(
    const std::filesystem::path& projectRoot, const ProjectManifestData& manifest,
    std::unordered_map<std::string, PackageNode>& outNodes,
    std::unordered_set<std::string>& outWorkspacePackageIds, std::string& outError) {
    for (const std::string& member : manifest.workspaceMembers) {
        const std::filesystem::path memberPath = projectRoot / member;
        if (!isDirectory(memberPath)) {
            outError = "Workspace member '" + member + "' does not exist.";
            return false;
        }

        PackageNode node;
        if (!loadPackageEntryFromDir(memberPath, node.entry, nullptr, outError)) {
            outError = "Could not load workspace member '" + member + "': " +
                       outError;
            return false;
        }
        if (!loadPackageManifestDependencies(memberPath, node.manifestDependencies,
                                             outError)) {
            outError = "Could not load workspace member '" + member + "': " +
                       outError;
            return false;
        }

        node.packageDir = std::filesystem::path(node.entry.packageDir);
        node.entry.sourceType = "workspace";
        node.entry.sourcePath = canonicalOrLexical(memberPath);
        if (!addAvailableNode(outNodes, node, outError)) {
            return false;
        }
        outWorkspacePackageIds.insert(node.entry.packageId);
    }

    return true;
}

const ProjectRegistryConfig* findRegistryConfig(
    const ProjectManifestData& manifest, std::string_view alias) {
    for (const auto& registry : manifest.registries) {
        if (registry.alias == alias) {
            return &registry;
        }
    }
    return nullptr;
}

const ProjectNativeToolchainConfig* findNativeToolchainConfig(
    const ProjectManifestData& manifest, std::string_view target) {
    for (const auto& toolchain : manifest.nativeToolchains) {
        if (toolchain.target == target) {
            return &toolchain;
        }
    }
    return nullptr;
}

bool packageIdsMatchDependencyPins(const std::vector<std::string>& manifestDeps,
                                   const std::vector<RegistryDependencyPin>& pins) {
    std::vector<std::string> pinnedIds;
    pinnedIds.reserve(pins.size());
    for (const auto& pin : pins) {
        pinnedIds.push_back(pin.packageId);
    }
    return sortedUniqueStrings(manifestDeps) == sortedUniqueStrings(std::move(pinnedIds));
}

bool findRegistryRecordForRequirement(const LoadedRegistryIndex& index,
                                      std::string_view packageId,
                                      const VersionRequirement& requirement,
                                      RegistryIndexRecord& outRecord,
                                      std::string& outError) {
    auto recordsIt = index.recordsByPackageId.find(std::string(packageId));
    if (recordsIt == index.recordsByPackageId.end()) {
        outError = "Registry does not contain '" + std::string(packageId) + "'.";
        return false;
    }

    for (const auto& record : recordsIt->second) {
        if (versionSatisfiesRequirement(record.parsedVersion, requirement)) {
            outRecord = record;
            return true;
        }
    }

    outError = "Registry does not contain a version of '" + std::string(packageId) +
               "' matching '" + requirement.raw + "'.";
    return false;
}

std::vector<RegistryIndexRecord> matchingRegistryRecords(
    const LoadedRegistryIndex& index, std::string_view packageId,
    const VersionRequirement& requirement) {
    std::vector<RegistryIndexRecord> matches;
    auto recordsIt = index.recordsByPackageId.find(std::string(packageId));
    if (recordsIt == index.recordsByPackageId.end()) {
        return matches;
    }

    for (const auto& record : recordsIt->second) {
        if (versionSatisfiesRequirement(record.parsedVersion, requirement)) {
            matches.push_back(record);
        }
    }
    return matches;
}

std::string availableNativeTargetsLabel(const RegistryIndexRecord& record) {
    std::vector<std::string> targets = record.nativeTargets;
    std::sort(targets.begin(), targets.end());
    targets.erase(std::unique(targets.begin(), targets.end()), targets.end());

    std::ostringstream out;
    for (size_t index = 0; index < targets.size(); ++index) {
        if (index != 0) {
            out << ", ";
        }
        out << targets[index];
    }
    return out.str();
}

bool resolveRegistryArtifactDirectory(const LoadedRegistryIndex& index,
                                      std::string_view registryAlias,
                                      std::string_view registryIndex,
                                      std::string_view rawArtifactPath,
                                      std::string_view artifactDigest,
                                      const InstallOptions* options,
                                      std::filesystem::path& outArtifactPath,
                                      std::string& outError) {
    outArtifactPath.clear();
    if (!index.isRemote) {
        if (!resolveManifestPath(index.rootDir.string(), std::string(rawArtifactPath),
                                 outArtifactPath, outError)) {
            return false;
        }
        outArtifactPath = canonicalOrLexical(outArtifactPath);
        if (!isDirectory(outArtifactPath)) {
            outError = "Registry artifact is missing at '" +
                       outArtifactPath.string() + "'.";
            return false;
        }
        return true;
    }

    const std::filesystem::path cacheDir =
        remoteRegistryArtifactCachePath(registryAlias, rawArtifactPath,
                                        artifactDigest);
    const bool offline = options != nullptr && options->offline;
    if (isDirectory(cacheDir) &&
        digestDirectory(cacheDir) == std::string(artifactDigest)) {
        outArtifactPath = cacheDir;
        return true;
    }
    if (offline) {
        outError = "Dependency '" + std::string(registryAlias) +
                   "' cannot be installed with --offline because registry artifact '" +
                   std::string(rawArtifactPath) + "' is not cached locally.";
        return false;
    }

    if (!removePathIfExists(cacheDir, outError)) {
        return false;
    }
    std::error_code ec;
    std::filesystem::create_directories(cacheDir, ec);
    if (ec) {
        outError = "Could not create registry artifact cache '" +
                   cacheDir.string() + "'.";
        return false;
    }

    std::string token;
    if (!resolveRegistryAuthTokenForIndex(registryAlias, registryIndex, token,
                                          outError)) {
        return false;
    }

    const std::string artifactRootUrl =
        joinUrlPath(index.remoteRootUrl, rawArtifactPath);
    const std::filesystem::path manifestPath = cacheDir / kArtifactManifestFileName;
    if (!downloadUrlToFile(joinUrlPath(artifactRootUrl, kArtifactManifestFileName),
                           token, manifestPath, outError)) {
        outError = "Registry artifact download failed for '" +
                   std::string(rawArtifactPath) + "': " + outError;
        return false;
    }

    std::vector<std::string> files;
    if (!parseArtifactManifest(manifestPath, files, outError)) {
        return false;
    }
    for (const auto& relative : files) {
        if (!downloadUrlToFile(joinUrlPath(artifactRootUrl, relative), token,
                               cacheDir / relative, outError)) {
            outError = "Registry artifact download failed for '" +
                       std::string(rawArtifactPath) + "': " + outError;
            return false;
        }
    }

    const std::string actualDigest = digestDirectory(cacheDir);
    if (actualDigest != artifactDigest) {
        outError = "Registry artifact digest mismatch for cached artifact '" +
                   std::string(rawArtifactPath) + "'.";
        return false;
    }

    outArtifactPath = cacheDir;
    return true;
}

bool selectRegistryArtifact(const RegistryIndexRecord& record,
                            std::string_view packageId,
                            const InstallOptions* options,
                            std::string& outArtifactPath,
                            std::string& outArtifactDigest,
                            std::string& outSelectedTarget,
                            std::string& outError) {
    outArtifactPath.clear();
    outArtifactDigest.clear();
    outSelectedTarget.clear();

    if (record.nativeTargets.empty()) {
        outArtifactPath = record.artifactPath;
        outArtifactDigest = record.artifactDigest;
        if (options != nullptr) {
            outSelectedTarget = effectiveInstallTarget(options);
        }
        return !outArtifactPath.empty() && !outArtifactDigest.empty();
    }

    const std::string desiredTarget = effectiveInstallTarget(options);
    auto targetIt = std::find(record.nativeTargets.begin(),
                              record.nativeTargets.end(), desiredTarget);
    if (targetIt != record.nativeTargets.end()) {
        const size_t index =
            static_cast<size_t>(std::distance(record.nativeTargets.begin(), targetIt));
        outArtifactPath = record.nativeArtifactPaths[index];
        outArtifactDigest = record.nativeArtifactDigests[index];
        outSelectedTarget = desiredTarget;
        return true;
    }

    if (options == nullptr && !record.nativeTargets.empty()) {
        outArtifactPath = record.nativeArtifactPaths.front();
        outArtifactDigest = record.nativeArtifactDigests.front();
        outSelectedTarget = record.nativeTargets.front();
        return true;
    }

    if (!record.artifactPath.empty() && !record.artifactDigest.empty()) {
        if (options != nullptr && options->noNativeBuild) {
            outError = "Registry package '" + std::string(packageId) +
                       "' does not publish a prebuilt native artifact for target '" +
                       desiredTarget + "'. Available targets: " +
                       availableNativeTargetsLabel(record) +
                       ". Source fallback is available in the registry entry, but --no-native-build forbids using it.";
            return false;
        }
        outArtifactPath = record.artifactPath;
        outArtifactDigest = record.artifactDigest;
        outSelectedTarget = desiredTarget;
        return true;
    }

    outError = "Registry package '" + std::string(packageId) +
               "' does not publish a native artifact for target '" +
               desiredTarget + "'. Available targets: " +
               availableNativeTargetsLabel(record) + ".";
    return false;
}

