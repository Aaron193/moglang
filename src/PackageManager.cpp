bool writeArtifactManifest(const std::filesystem::path& artifactDir,
                           std::string& outError) {
    std::vector<std::string> files;
    std::error_code ec;
    for (std::filesystem::recursive_directory_iterator it(artifactDir, ec), end;
         !ec && it != end; it.increment(ec)) {
        if (!it->is_regular_file(ec) || ec) {
            continue;
        }
        const std::filesystem::path relative =
            it->path().lexically_relative(artifactDir);
        if (relative == kArtifactManifestFileName) {
            continue;
        }
        files.push_back(normalizeRelativePath(relative.lexically_normal().string()));
    }
    if (ec) {
        outError = "Could not enumerate artifact files under '" +
                   artifactDir.string() + "'.";
        return false;
    }

    files = sortedUniqueStrings(std::move(files));
    std::ofstream out(artifactDir / kArtifactManifestFileName);
    if (!out) {
        outError = "Could not write artifact manifest under '" +
                   artifactDir.string() + "'.";
        return false;
    }
    out << "files = " << quoteTomlArray(files) << "\n";
    return true;
}

bool parseArtifactManifest(const std::filesystem::path& manifestPath,
                           std::vector<std::string>& outFiles,
                           std::string& outError) {
    outFiles.clear();
    std::ifstream file(manifestPath);
    if (!file) {
        outError = "Could not open artifact manifest '" + manifestPath.string() +
                   "'.";
        return false;
    }

    std::string line;
    size_t lineNumber = 0;
    while (std::getline(file, line)) {
        ++lineNumber;
        const std::string content = stripComment(line);
        if (content.empty()) {
            continue;
        }

        const size_t equals = content.find('=');
        if (equals == std::string::npos) {
            outError = "Invalid artifact manifest line " +
                       std::to_string(lineNumber) + ": expected key = value.";
            return false;
        }
        const std::string key = trim(std::string_view(content).substr(0, equals));
        const std::string value =
            trim(std::string_view(content).substr(equals + 1));
        if (key != "files") {
            outError = "Unsupported artifact manifest field '" + key + "'.";
            return false;
        }
        if (!parseQuotedStringArray(value, outFiles, outError)) {
            outError = "Invalid artifact manifest line " +
                       std::to_string(lineNumber) + ": " + outError;
            return false;
        }
        outFiles = sortedUniqueStrings(std::move(outFiles));
        return true;
    }

    outError = "Artifact manifest is missing files = [...].";
    return false;
}

bool loadLegacyRegistryAuthTokens(
    std::unordered_map<std::string, std::string>& outTokens,
    std::string& outError) {
    outTokens.clear();
    outError.clear();

    const std::filesystem::path authPath = registryAuthPath();
    if (!fileExists(authPath)) {
        return true;
    }

    std::ifstream file(authPath);
    if (!file) {
        outError = "Could not open registry auth file '" + authPath.string() + "'.";
        return false;
    }

    std::string currentAlias;
    std::string line;
    size_t lineNumber = 0;
    while (std::getline(file, line)) {
        ++lineNumber;
        const std::string content = stripComment(line);
        if (content.empty()) {
            continue;
        }
        if (content.front() == '[' && content.back() == ']') {
            const std::string section = content.substr(1, content.size() - 2);
            const std::string prefix = "registries.";
            currentAlias =
                section.rfind(prefix, 0) == 0 ? section.substr(prefix.size()) : "";
            continue;
        }

        const size_t equals = content.find('=');
        if (equals == std::string::npos) {
            outError = "Invalid registry auth line " + std::to_string(lineNumber) +
                       ": expected key = value.";
            return false;
        }
        if (currentAlias.empty()) {
            continue;
        }

        const std::string key = trim(std::string_view(content).substr(0, equals));
        const std::string value =
            trim(std::string_view(content).substr(equals + 1));
        if (key != "token") {
            continue;
        }
        std::string token;
        if (!parseQuotedString(value, token, outError)) {
            outError = "Invalid registry auth line " +
                       std::to_string(lineNumber) + ": " + outError;
            return false;
        }
        outTokens[currentAlias] = token;
    }

    return true;
}

bool flushUserRegistryProfile(UserRegistryConfigData& outConfig,
                              UserRegistryProfile& current,
                              bool hasSection,
                              std::string& outError) {
    if (!hasSection) {
        return true;
    }
    if (current.index.empty()) {
        outError = "Stored registries must define index = \"...\".";
        return false;
    }

    current.trustedKeys = sortedUniqueStrings(std::move(current.trustedKeys));
    UserRegistryProfile* existing =
        upsertUserRegistryProfile(outConfig, current.index);
    existing->trustedKeys = sortedUniqueStrings(
        std::vector<std::string>(existing->trustedKeys.begin(),
                                 existing->trustedKeys.end()));
    existing->trustedKeys.insert(existing->trustedKeys.end(),
                                 current.trustedKeys.begin(),
                                 current.trustedKeys.end());
    existing->trustedKeys = sortedUniqueStrings(std::move(existing->trustedKeys));
    if (!current.token.empty()) {
        existing->token = current.token;
    }
    return true;
}

bool loadUserRegistryProfiles(UserRegistryConfigData& outConfig,
                              std::string& outError) {
    outConfig = UserRegistryConfigData{};
    outError.clear();

    const std::filesystem::path configPath = registryProfilesPath();
    if (!fileExists(configPath)) {
        return true;
    }

    std::ifstream file(configPath);
    if (!file) {
        outError = "Could not open registry profile file '" + configPath.string() +
                   "'.";
        return false;
    }

    UserRegistryProfile current;
    bool inRegistry = false;
    std::string line;
    size_t lineNumber = 0;
    while (std::getline(file, line)) {
        ++lineNumber;
        const std::string content = stripComment(line);
        if (content.empty()) {
            continue;
        }
        if (content == "[[registry]]") {
            if (!flushUserRegistryProfile(outConfig, current, inRegistry, outError)) {
                return false;
            }
            current = UserRegistryProfile{};
            inRegistry = true;
            continue;
        }
        if (content.front() == '[' && content.back() == ']') {
            outError = "Unsupported registry profile section '" + content + "'.";
            return false;
        }
        if (!inRegistry) {
            outError = "Registry profile fields must appear inside [[registry]].";
            return false;
        }

        const size_t equals = content.find('=');
        if (equals == std::string::npos) {
            outError = "Invalid registry profile line " +
                       std::to_string(lineNumber) + ": expected key = value.";
            return false;
        }
        const std::string key = trim(std::string_view(content).substr(0, equals));
        const std::string value =
            trim(std::string_view(content).substr(equals + 1));
        std::string parseError;
        if (key == "index") {
            if (!parseQuotedString(value, current.index, parseError)) {
                outError = "Invalid registry profile field '" + key + "': " +
                           parseError;
                return false;
            }
        } else if (key == "trusted_keys") {
            if (!parseQuotedStringArray(value, current.trustedKeys, parseError)) {
                outError = "Invalid registry profile field '" + key + "': " +
                           parseError;
                return false;
            }
        } else if (key == "token") {
            if (!parseQuotedString(value, current.token, parseError)) {
                outError = "Invalid registry profile field '" + key + "': " +
                           parseError;
                return false;
            }
        } else {
            outError = "Unsupported registry profile field '" + key + "'.";
            return false;
        }
    }

    if (!flushUserRegistryProfile(outConfig, current, inRegistry, outError)) {
        return false;
    }
    sortUserRegistryProfiles(outConfig.registries);
    return true;
}

bool writeUserRegistryProfiles(const UserRegistryConfigData& config,
                               std::string& outError) {
    const std::filesystem::path configPath = registryProfilesPath();
    std::error_code ec;
    std::filesystem::create_directories(configPath.parent_path(), ec);
    if (ec) {
        outError = "Could not create registry profile directory '" +
                   configPath.parent_path().string() + "'.";
        return false;
    }

    std::ofstream out(configPath);
    if (!out) {
        outError = "Could not open registry profile file '" + configPath.string() +
                   "' for writing.";
        return false;
    }

    std::vector<UserRegistryProfile> registries = config.registries;
    sortUserRegistryProfiles(registries);
    bool first = true;
    for (const auto& registry : registries) {
        if (registry.index.empty() ||
            (registry.trustedKeys.empty() && registry.token.empty())) {
            continue;
        }
        if (!first) {
            out << "\n";
        }
        first = false;
        out << "[[registry]]\n";
        out << "index = " << quoteTomlString(registry.index) << "\n";
        if (!registry.trustedKeys.empty()) {
            out << "trusted_keys = "
                << quoteTomlArray(sortedUniqueStrings(registry.trustedKeys))
                << "\n";
        }
        if (!registry.token.empty()) {
            out << "token = " << quoteTomlString(registry.token) << "\n";
        }
    }
    return true;
}

bool downloadUrlToFile(std::string_view url, const std::string& token,
                       const std::filesystem::path& destination,
                       std::string& outError) {
    if (!ensureParentDirectory(destination, outError)) {
        return false;
    }

    std::ostringstream command;
    command << "curl -fsSL ";
    if (!token.empty()) {
        command << "-H "
                << shellQuote("Authorization: Bearer " + token) << " ";
    }
    command << "-o " << shellQuote(destination.string()) << " "
            << shellQuote(std::string(url));

    std::string output;
    if (!runCapturedSystemCommand(command.str(), output, outError)) {
        outError = trim(output).empty() ? "curl download failed." : trim(output);
        return false;
    }

    return true;
}

bool uploadFileToUrl(const std::filesystem::path& source, std::string_view url,
                     const std::string& token, std::string& outError) {
    std::ostringstream command;
    command << "curl -fsSL -X PUT ";
    if (!token.empty()) {
        command << "-H "
                << shellQuote("Authorization: Bearer " + token) << " ";
    }
    command << "--upload-file " << shellQuote(source.string()) << " "
            << shellQuote(std::string(url));

    std::string output;
    if (!runCapturedSystemCommand(command.str(), output, outError)) {
        outError = trim(output).empty() ? "curl upload failed." : trim(output);
        return false;
    }
    return true;
}

bool uploadDirectoryToUrl(const std::filesystem::path& sourceDir,
                          std::string_view destinationUrl,
                          const std::string& token, std::string& outError) {
    std::error_code ec;
    for (std::filesystem::recursive_directory_iterator it(sourceDir, ec), end;
         !ec && it != end; it.increment(ec)) {
        if (!it->is_regular_file(ec) || ec) {
            continue;
        }
        const std::filesystem::path relative =
            it->path().lexically_relative(sourceDir);
        if (!uploadFileToUrl(it->path(),
                             joinUrlPath(std::string(destinationUrl),
                                         normalizeRelativePath(
                                             relative.lexically_normal().string())),
                             token, outError)) {
            return false;
        }
    }
    if (ec) {
        outError = "Could not enumerate publish directory '" +
                   sourceDir.string() + "'.";
        return false;
    }
    return true;
}

std::string inferWorkspaceRoot(const std::filesystem::path& packageDir,
                               const PackageRegistryEntry& entry,
                               const std::string& fallbackProjectRoot) {
    std::filesystem::path current = packageDir;
    while (!current.empty()) {
        const std::filesystem::path candidateLibrary =
            current / "build" / "packages" / entry.packageNamespace /
            entry.packageName / kPackageLibraryFileName;
        if (fileExists(candidateLibrary)) {
            return current.string();
        }
        if (current == current.root_path()) {
            break;
        }
        current = current.parent_path();
    }

    return fallbackProjectRoot;
}

bool loadPackageEntryFromDir(const std::filesystem::path& packageDir,
                             PackageRegistryEntry& outEntry,
                             std::vector<std::string>* outDependencies,
                             std::string& outError) {
    PackageManifest manifest;
    if (!loadPackageManifest(packageDir.string(), manifest, outError)) {
        return false;
    }

    outEntry = PackageRegistryEntry{};
    outEntry.importName = manifest.importName.empty() ? manifest.packageName
                                                      : manifest.importName;
    outEntry.packageNamespace = manifest.packageNamespace;
    outEntry.packageName = manifest.packageName;
    outEntry.packageId = makePackageId(manifest.packageNamespace, manifest.packageName);
    outEntry.version = manifest.version;
    outEntry.packageDir = canonicalOrLexical(packageDir);
    outEntry.kind = manifest.kind.empty() ? "native" : manifest.kind;
    outEntry.description = manifest.description;
    outEntry.dependencyIds.clear();
    for (const auto& dependency : manifest.dependencies) {
        outEntry.dependencyIds.push_back(dependency.packageId);
    }
    outEntry.sourceType = "path";
    outEntry.sourcePath = canonicalOrLexical(packageDir);
    outEntry.manifestDigest = manifestDigestForDir(packageDir);

    if (outEntry.kind == "source") {
        std::filesystem::path entryPath = manifest.entry.empty()
                                              ? packageDir / "src" / "main.mog"
                                              : packageDir / manifest.entry;
        outEntry.entryPath = canonicalOrLexical(entryPath);
    } else if (!manifest.library.empty()) {
        const std::filesystem::path configuredLibrary = packageDir / manifest.library;
        if (fileExists(configuredLibrary)) {
            outEntry.libraryPath = canonicalOrLexical(configuredLibrary);
        }
    } else {
        const std::filesystem::path directLibrary =
            packageDir / kPackageLibraryFileName;
        if (fileExists(directLibrary)) {
            outEntry.libraryPath = canonicalOrLexical(directLibrary);
        }
    }

    const std::filesystem::path apiPath = packageDir / kPackageApiFileName;
    if (fileExists(apiPath)) {
        outEntry.apiPath = canonicalOrLexical(apiPath);
        outEntry.apiDigest = digestFile(apiPath);
    }

    if (outDependencies != nullptr) {
        *outDependencies = outEntry.dependencyIds;
    }

    return true;
}

