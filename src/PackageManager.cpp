bool addAvailableNode(std::unordered_map<std::string, PackageNode>& outNodes,
                      PackageNode node, std::string& outError) {
    auto existing = outNodes.find(node.entry.packageId);
    if (existing != outNodes.end()) {
        if (existing->second.packageDir != node.packageDir) {
            outError = "Duplicate local package '" + node.entry.packageId +
                       "' found at '" + existing->second.packageDir.string() +
                       "' and '" + node.packageDir.string() + "'.";
            return false;
        }
        return true;
    }

    outNodes[node.entry.packageId] = std::move(node);
    return true;
}

bool resolveManifestPath(const std::string& projectRoot,
                         const std::string& rawPath,
                         std::filesystem::path& outPath,
                         std::string& outError) {
    outError.clear();
    if (rawPath.rfind("file://", 0) == 0) {
        outPath = std::filesystem::path(rawPath.substr(7));
        return true;
    }

    const std::filesystem::path candidate(rawPath);
    if (candidate.is_absolute()) {
        outPath = candidate;
        return true;
    }

    if (rawPath.empty()) {
        outError = "Registry index path cannot be empty.";
        return false;
    }

    outPath = std::filesystem::path(projectRoot) / candidate;
    return true;
}

bool resolveRegistryLocation(const std::string& projectRoot,
                             const ProjectRegistryConfig& config,
                             RegistryLocation& outLocation,
                             std::string& outError) {
    outLocation = RegistryLocation{};
    outError.clear();

    if (config.index.empty()) {
        outError = "Registry index path cannot be empty.";
        return false;
    }

    if (isHttpUrl(config.index)) {
        outLocation.isRemote = true;
        outLocation.remoteIndexUrl = normalizeRegistryIndexUrl(config.index);
        outLocation.remoteRootUrl = parentUrl(outLocation.remoteIndexUrl);
        outLocation.localIndexPath =
            remoteRegistryIndexCachePath(config.alias, outLocation.remoteIndexUrl);
        outLocation.localRootDir = outLocation.localIndexPath.parent_path();
        return true;
    }

    if (!resolveManifestPath(projectRoot, config.index, outLocation.localIndexPath,
                             outError)) {
        return false;
    }

    std::error_code ec;
    if (std::filesystem::is_directory(outLocation.localIndexPath, ec) && !ec) {
        outLocation.localIndexPath /= "index.toml";
    }
    outLocation.localIndexPath =
        std::filesystem::weakly_canonical(outLocation.localIndexPath, ec);
    if (ec) {
        outLocation.localIndexPath = outLocation.localIndexPath.lexically_normal();
        ec.clear();
    }
    outLocation.localRootDir = outLocation.localIndexPath.parent_path();
    return true;
}

bool resolveRegistryIdentity(const std::string& projectRoot,
                             const ProjectRegistryConfig& config,
                             std::string& outIdentity,
                             bool& outIsRemote,
                             std::string& outError) {
    RegistryLocation location;
    if (!resolveRegistryLocation(projectRoot, config, location, outError)) {
        return false;
    }

    outIsRemote = location.isRemote;
    outIdentity = location.isRemote
                      ? location.remoteIndexUrl
                      : normalizeRelativePath(
                            location.localIndexPath.lexically_normal().string());
    return true;
}

