bool registryRequiresTrustedSignatures(const ProjectRegistryConfig& config,
                                       bool isRemote) {
    return !config.trustedKeys.empty() || (isRemote && !config.allowInsecure);
}

bool verifyRegistrySignatureEnvelope(const ProjectRegistryConfig& config,
                                     bool isRemote,
                                     std::string_view signingKeyId,
                                     std::string_view signatureBase64,
                                     std::string_view canonicalPayload,
                                     std::string& outError) {
    if (!registryRequiresTrustedSignatures(config, isRemote)) {
        return true;
    }
    if (signingKeyId.empty() || signatureBase64.empty()) {
        outError = "Registry '" + config.alias +
                   "' requires a signed index, but the registry metadata is unsigned.";
        return false;
    }
    if (config.trustedKeys.empty()) {
        outError = "Registry '" + config.alias +
                   "' requires trusted_keys unless allow_insecure = true is set.";
        return false;
    }

    RegistryTrustedKey trustedKey;
    bool foundKey = false;
    for (const std::string& rawTrustedKey : config.trustedKeys) {
        RegistryTrustedKey parsedKey;
        if (!parseTrustedRegistryKey(rawTrustedKey, parsedKey, outError)) {
            outError = "Registry '" + config.alias + "' has invalid trusted_keys: " +
                       outError;
            return false;
        }
        if (parsedKey.keyId == signingKeyId) {
            trustedKey = std::move(parsedKey);
            foundKey = true;
            break;
        }
    }
    if (!foundKey) {
        outError = "Registry '" + config.alias + "' was signed by unknown key '" +
                   std::string(signingKeyId) + "'.";
        return false;
    }

    if (!verifyEd25519Message(trustedKey.publicKeyDerBase64, canonicalPayload,
                              signatureBase64, outError)) {
        outError = "Registry '" + config.alias + "' signature verification failed: " +
                   outError;
        return false;
    }
    return true;
}

bool removePathIfExists(const std::filesystem::path& path, std::string& outError) {
    std::error_code ec;
    if (!std::filesystem::exists(path, ec) && !std::filesystem::is_symlink(path, ec)) {
        return true;
    }
    std::filesystem::remove_all(path, ec);
    if (ec) {
        outError = "Could not remove '" + path.string() + "'.";
        return false;
    }
    return true;
}

bool ensureParentDirectory(const std::filesystem::path& path, std::string& outError) {
    std::error_code ec;
    std::filesystem::create_directories(path.parent_path(), ec);
    if (ec) {
        outError = "Could not create directory '" + path.parent_path().string() + "'.";
        return false;
    }
    return true;
}

bool copyFileReplacing(const std::filesystem::path& from,
                       const std::filesystem::path& to,
                       std::string& outError) {
    if (!ensureParentDirectory(to, outError)) {
        return false;
    }

    std::error_code ec;
    std::filesystem::copy_file(from, to,
                               std::filesystem::copy_options::overwrite_existing,
                               ec);
    if (ec) {
        outError = "Could not copy '" + from.string() + "' to '" + to.string() + "'.";
        return false;
    }
    return true;
}

bool copyDirectoryRecursive(const std::filesystem::path& from,
                            const std::filesystem::path& to,
                            std::string& outError) {
    std::error_code ec;
    std::filesystem::create_directories(to, ec);
    if (ec) {
        outError = "Could not create directory '" + to.string() + "'.";
        return false;
    }

    std::filesystem::recursive_directory_iterator it(from, ec), end;
    for (; !ec && it != end; it.increment(ec)) {
        const std::filesystem::path relative = it->path().lexically_relative(from);
        const std::filesystem::path destination = to / relative;
        if (it->is_directory(ec)) {
            std::filesystem::create_directories(destination, ec);
            if (ec) {
                outError = "Could not create directory '" + destination.string() + "'.";
                return false;
            }
            continue;
        }

        if (!it->is_regular_file(ec)) {
            continue;
        }

        if (!copyFileReplacing(it->path(), destination, outError)) {
            return false;
        }
    }

    if (ec) {
        outError = "Could not copy directory '" + from.string() + "'.";
        return false;
    }

    return true;
}

